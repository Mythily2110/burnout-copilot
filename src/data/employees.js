export function calculateBurnout(employee) {
  const seniorityScore =
    employee.designation === 'Junior' ? 10 : employee.designation === 'Mid' ? 5 : 0;

  const score =
    (employee.mentalFatigueScore / 10) * 35 +
    (employee.resourceAllocation / 10) * 25 +
    (Math.max(0, employee.weeklyHours - 40) / 30) * 20 +
    ((15 - employee.ptoUsed) / 15) * 10 +
    seniorityScore;

  const roundedScore = Math.min(100, Math.max(0, Math.round(score)));

  return {
    score: roundedScore,
    riskLevel:
      roundedScore < 40 ? 'Low' : roundedScore < 70 ? 'Medium' : 'High',
  };
}

